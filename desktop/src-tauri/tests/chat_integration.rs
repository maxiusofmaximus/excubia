#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn the_team_chain_works_against_the_test_profile_host() {
    let Some((team_host, test_cli)) = team_host_paths() else {
        eprintln!("saltado: falta target/team-host o HN_TEAM_HOST/HN_TEST_CLI");
        return;
    };
    let data_dir = temp_dir("team-chain");
    let Some(host) =
        start_host_binary(team_host, data_dir.clone(), None, Some(test_cli.clone())).await
    else {
        eprintln!("saltado: no arrancó el host de pruebas");
        return;
    };
    let (_, client) = pair_and_grant(&host, true).await;
    let conversation = client
        .chat_create_conversation(Some("Equipo"))
        .await
        .expect("crear conversación");
    client
        .chat_send(
            &conversation.id,
            "team-chain",
            "[[fake:team]] crea el proyecto Demo y pide a Ernesto un plan de 3 hitos",
        )
        .await
        .expect("enviar al equipo");

    let cards = wait_for_cards(&client, &conversation.id, |cards| !cards.is_empty()).await;
    let parent = cards
        .iter()
        .find(|card| {
            card.title
                .as_deref()
                .is_some_and(|title| title.contains("Ernesto"))
        })
        .unwrap_or(&cards[0]);
    let parent_id = card_id(parent).expect("id de la delegación padre");
    assert_eq!(parent.kind, "card");

    let parent_detail = client
        .chat_delegation(&parent_id)
        .await
        .expect("detalle padre");
    assert_eq!(parent_detail.delegation.from_name, "Alfred");
    assert_eq!(parent_detail.delegation.to_name, "Ernesto");
    assert_eq!(parent_detail.delegation.depth, 1);
    assert!(parent_detail.delegation.project_id.is_some());

    let cards = wait_for_cards(&client, &conversation.id, |cards| {
        cards.len() >= 2
            && cards
                .iter()
                .any(|card| card_id(card).as_deref() != Some(parent_id.as_str()))
    })
    .await;
    let child = cards
        .iter()
        .find(|card| card_id(card).as_deref() != Some(parent_id.as_str()))
        .expect("tarjeta del hijo");
    let child_id = card_id(child).expect("id de la delegación hija");
    assert!(
        child.title.is_some(),
        "la tarjeta del hijo debe existir: {child:?}"
    );

    let child_detail = client
        .chat_delegation(&child_id)
        .await
        .expect("detalle hijo");
    assert_eq!(child_detail.delegation.depth, 2);
    assert_eq!(child_detail.delegation.from_name, "Ernesto");
    assert_eq!(child_detail.delegation.to_name, "Bob");
    assert_eq!(
        child_detail.delegation.parent_id.as_deref(),
        Some(parent_id.as_str())
    );
    let deadline = tokio::time::Instant::now() + Duration::from_secs(30);
    while tokio::time::Instant::now() < deadline {
        let detail = client
            .chat_delegation(&child_id)
            .await
            .expect("detalle hijo");
        if detail.delegation.state == "done" {
            assert!(detail.result_message.is_some());
            break;
        }
        tokio::time::sleep(Duration::from_millis(100)).await;
    }

    let bootstrap = client.chat_bootstrap().await.expect("bootstrap");
    assert!(bootstrap
        .projects
        .iter()
        .any(|project| project.name == "Demo"
            && project
                .lead
                .as_ref()
                .is_some_and(|lead| lead.name == "Ernesto")));

    let refused = client
        .chat_cancel_delegation(&parent_id)
        .await
        .expect_err("una delegación terminada no se cancela");
    match refused {
        ChatFailure::DelegationRefused { code, .. } => assert_eq!(code, "delegation_cancelled"),
        other => panic!("esperaba delegation_cancelled, llegó {other:?}"),
    }

    host.stop().await;
    std::fs::remove_dir_all(data_dir).ok();
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn cancelling_and_restarting_keep_the_delegation_card() {
    let Some((team_host, test_cli)) = team_host_paths() else {
        eprintln!("saltado: falta target/team-host o HN_TEAM_HOST/HN_TEST_CLI");
        return;
    };
    let data_dir = temp_dir("team-cancel");
    let Some(host) = start_host_binary(
        team_host.clone(),
        data_dir.clone(),
        None,
        Some(test_cli.clone()),
    )
    .await
    else {
        eprintln!("saltado: no arrancó el host de pruebas");
        return;
    };
    let (_, client) = pair_and_grant(&host, true).await;
    let conversation = client
        .chat_create_conversation(Some("Equipo"))
        .await
        .expect("crear conversación");
    client
        .chat_send(
            &conversation.id,
            "team-cancel",
            "[[fake:team]] [[fake:silent]] deja el plan pendiente",
        )
        .await
        .expect("enviar al equipo");
    let cards = wait_for_cards(&client, &conversation.id, |cards| !cards.is_empty()).await;
    let parent_id = card_id(&cards[0]).expect("id de la delegación");
    let detail = client.chat_delegation(&parent_id).await.expect("detalle");
    assert!(["queued", "running", "waiting"].contains(&detail.delegation.state.as_str()));

    let cancelled = client
        .chat_cancel_delegation(&parent_id)
        .await
        .expect("cancelar una delegación activa");
    assert_eq!(cancelled.delegation.state, "cancelled");
    let cards = wait_for_cards(&client, &conversation.id, |cards| {
        cards.iter().any(|card| {
            card_id(card).as_deref() == Some(parent_id.as_str())
                && card.status.as_deref() == Some("cancelled")
        })
    })
    .await;
    assert!(cards
        .iter()
        .any(|card| card_id(card).as_deref() == Some(parent_id.as_str())));

    host.stop().await;
    std::fs::remove_dir_all(data_dir).ok();

    // A separate host: active work becomes interrupted after a restart.
    let restart_dir = temp_dir("team-restart");
    let Some(restart_host) = start_host_binary(
        team_host.clone(),
        restart_dir.clone(),
        None,
        Some(test_cli.clone()),
    )
    .await
    else {
        panic!("no arrancó el host de reinicio");
    };
    let (restart_identity, restart_client) = pair_and_grant(&restart_host, true).await;
    let fresh = restart_client
        .chat_create_conversation(Some("Interrumpida"))
        .await
        .expect("crear conversación");
    restart_client
        .chat_send(
            &fresh.id,
            "team-restart",
            "[[fake:team]] [[fake:silent]] otra tarea pendiente",
        )
        .await
        .expect("enviar");
    let cards = wait_for_cards(&restart_client, &fresh.id, |cards| !cards.is_empty()).await;
    let running_id = card_id(&cards[0]).expect("id de la tarea");
    restart_host.stop().await;
    let Some(restart_host) =
        start_host_binary(team_host, restart_dir.clone(), None, Some(test_cli)).await
    else {
        panic!("el host de pruebas no volvió a arrancar");
    };
    let restart_client = GatewayClient::new(&restart_host.url(), restart_identity).expect("client");
    let interrupted = restart_client
        .chat_delegation(&running_id)
        .await
        .expect("detalle tras reinicio");
    assert_eq!(interrupted.delegation.state, "interrupted");
    assert_eq!(
        interrupted.delegation.reason.as_deref(),
        Some("host_restart")
    );

    restart_host.stop().await;
    std::fs::remove_dir_all(restart_dir).ok();
}
